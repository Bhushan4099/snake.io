GW, GH = 5, 7          # glyph cells
ADVANCE = GW + 1       # one empty column between characters


class PixelFont:
    """render(text, antialias, color) -> Surface, same call shape as pygame.font.Font."""

    def __init__(self, scale=2):
        self.scale = scale
        self._cache = {}

    def _glyph(self, ch, color):
        key = (ch, color)
        if key not in self._cache:
            s = self.scale
            surf = pygame.Surface((GW * s, GH * s), pygame.SRCALPHA)
            for row, line in enumerate(GLYPHS.get(ch, GLYPHS["?"])):
                for col, c in enumerate(line):
                    if c == "#":
                        surf.fill(color, (col * s, row * s, s, s))
            self._cache[key] = surf
        return self._cache[key]

    def size(self, text):
        return (max(len(text) * ADVANCE - 1, 0) * self.scale, GH * self.scale)

    def render(self, text, _antialias=False, color=(255, 255, 255)):
        text = str(text).upper()
        surf = pygame.Surface(self.size(text) if text else (1, GH * self.scale), pygame.SRCALPHA)
        color = tuple(color)
        for i, ch in enumerate(text):
            if ch != " ":
                surf.blit(self._glyph(ch, color), (i * ADVANCE * self.scale, 0))
        return surf
